-- --------------------------------------------------------------------------
-- 9. INTEGRACIÓN SUPABASE AUTH (Sincronización automática auth.users -> public.usuarios)
-- Nota de Seguridad: Nunca usa raw_user_meta_data para asignar roles; el rol
-- autoritativo solo proviene de raw_app_meta_data o por defecto 'cliente'.
-- --------------------------------------------------------------------------
DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1 FROM information_schema.tables
    WHERE table_schema = 'auth' AND table_name = 'users'
  ) THEN
    CREATE TABLE auth.users (
      id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
      email TEXT UNIQUE,
      encrypted_password TEXT,
      raw_user_meta_data JSONB DEFAULT '{}'::jsonb,
      raw_app_meta_data JSONB DEFAULT '{}'::jsonb,
      created_at TIMESTAMPTZ DEFAULT timezone('utc'::text, now())
    );
  END IF;
END
$$;

CREATE OR REPLACE FUNCTION public.handle_new_auth_user()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public
AS $$
DECLARE
  v_rol VARCHAR(20);
  v_nombre VARCHAR(120);
  v_telefono VARCHAR(30);
  v_direccion TEXT;
BEGIN
  -- El rol solo puede provenir de raw_app_meta_data (nunca de raw_user_meta_data editable por el usuario)
  v_rol := COALESCE(NEW.raw_app_meta_data ->> 'rol', 'cliente');
  IF v_rol NOT IN ('cliente', 'admin', 'gestor') THEN
    v_rol := 'cliente';
  END IF;

  v_nombre := COALESCE(
    NULLIF(TRIM(NEW.raw_user_meta_data ->> 'nombre'), ''),
    NULLIF(TRIM(NEW.raw_user_meta_data ->> 'full_name'), ''),
    SPLIT_PART(NEW.email, '@', 1)
  );
  v_telefono := NULLIF(TRIM(NEW.raw_user_meta_data ->> 'telefono'), '');
  v_direccion := NULLIF(TRIM(NEW.raw_user_meta_data ->> 'direccion'), '');

  INSERT INTO public.usuarios (auth_user_id, nombre, email, password_hash, telefono, direccion, rol, activo)
  VALUES (
    NEW.id,
    v_nombre,
    LOWER(NEW.email),
    COALESCE(NEW.encrypted_password, 'SUPABASE_AUTH_MANAGED'),
    v_telefono,
    v_direccion,
    v_rol,
    true
  )
  ON CONFLICT (email) DO UPDATE SET
    auth_user_id = EXCLUDED.auth_user_id,
    actualizado_en = timezone('utc'::text, now());

  RETURN NEW;
END;
$$;

-- Bloquear invocación pública por RPC de la función SECURITY DEFINER (Supabase Security Checklist)
REVOKE ALL ON FUNCTION public.handle_new_auth_user() FROM PUBLIC, anon, authenticated;

DO $$
BEGIN
  DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
  CREATE TRIGGER on_auth_user_created
    AFTER INSERT ON auth.users
    FOR EACH ROW
    EXECUTE FUNCTION public.handle_new_auth_user();
EXCEPTION
  WHEN insufficient_privilege THEN
    RAISE NOTICE 'Trigger on_auth_user_created omitido por privilegios sobre auth.users';
END
$$;

