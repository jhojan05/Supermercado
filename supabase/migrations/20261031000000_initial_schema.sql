-- 2. DEFINICIÓN DE TABLAS EN ESQUEMA PUBLIC (FORMATO SUPABASE)
-- --------------------------------------------------------------------------

-- 2.1 Tabla de Usuarios / Perfiles (Clientes y Administradores)
CREATE TABLE IF NOT EXISTS public.usuarios (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid UUID DEFAULT gen_random_uuid() UNIQUE NOT NULL,
  auth_user_id UUID UNIQUE, -- Vínculo opcional con auth.users(id) de Supabase Auth
  nombre VARCHAR(120) NOT NULL,
  email VARCHAR(160) UNIQUE NOT NULL,
  password_hash VARCHAR(255) NOT NULL,
  telefono VARCHAR(30),
  direccion TEXT,
  rol VARCHAR(20) DEFAULT 'cliente' CHECK (rol IN ('cliente', 'admin', 'gestor')),
  activo BOOLEAN DEFAULT true,
  creado_en TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  actualizado_en TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2.2 Tabla de Categorías
CREATE TABLE IF NOT EXISTS public.categorias (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid UUID DEFAULT gen_random_uuid() UNIQUE NOT NULL,
  nombre VARCHAR(80) UNIQUE NOT NULL,
  slug VARCHAR(80) UNIQUE NOT NULL,
  descripcion TEXT,
  icono VARCHAR(60),
  orden INT DEFAULT 0,
  activa BOOLEAN DEFAULT true,
  creado_en TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2.3 Tabla de Productos
CREATE TABLE IF NOT EXISTS public.productos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid UUID DEFAULT gen_random_uuid() UNIQUE NOT NULL,
  categoria_id BIGINT REFERENCES public.categorias(id) ON DELETE SET NULL,
  nombre VARCHAR(200) NOT NULL,
  categoria_nombre VARCHAR(80) NOT NULL,
  presentacion VARCHAR(120) NOT NULL,
  precio NUMERIC(12, 2) NOT NULL CHECK (precio >= 0),
  precio_anterior NUMERIC(12, 2) CHECK (precio_anterior IS NULL OR precio_anterior >= 0),
  imagen VARCHAR(255) NOT NULL,
  disponible BOOLEAN DEFAULT true,
  destacado BOOLEAN DEFAULT false,
  badge VARCHAR(50),
  origen VARCHAR(120),
  stock INT DEFAULT 100 CHECK (stock >= 0),
  creado_en TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  actualizado_en TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2.4 Tabla de Pedidos
CREATE TABLE IF NOT EXISTS public.pedidos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid UUID DEFAULT gen_random_uuid() UNIQUE NOT NULL,
  codigo_orden VARCHAR(40) UNIQUE NOT NULL,
  usuario_id BIGINT REFERENCES public.usuarios(id) ON DELETE SET NULL,
  cliente_nombre VARCHAR(120) NOT NULL,
  cliente_telefono VARCHAR(40) NOT NULL,
  cliente_direccion TEXT NOT NULL,
  notas TEXT,
  metodo_pago VARCHAR(60) NOT NULL,
  subtotal NUMERIC(12, 2) NOT NULL CHECK (subtotal >= 0),
  descuento NUMERIC(12, 2) DEFAULT 0 CHECK (descuento >= 0),
  total NUMERIC(12, 2) NOT NULL CHECK (total >= 0),
  estado VARCHAR(30) DEFAULT 'pendiente' CHECK (estado IN ('pendiente', 'confirmado', 'en_preparacion', 'en_camino', 'entregado', 'cancelado')),
  creado_en TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  actualizado_en TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

-- 2.5 Tabla de Ítems del Pedido
CREATE TABLE IF NOT EXISTS public.pedido_items (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  pedido_id BIGINT NOT NULL REFERENCES public.pedidos(id) ON DELETE CASCADE,
  producto_id BIGINT REFERENCES public.productos(id) ON DELETE SET NULL,
  nombre_producto VARCHAR(200) NOT NULL,
  cantidad INT NOT NULL CHECK (cantidad > 0),
  precio_unitario NUMERIC(12, 2) NOT NULL CHECK (precio_unitario >= 0),
  total_linea NUMERIC(12, 2) NOT NULL CHECK (total_linea >= 0)
);

-- 2.6 Tabla de Favoritos
CREATE TABLE IF NOT EXISTS public.favoritos (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  usuario_id BIGINT NOT NULL REFERENCES public.usuarios(id) ON DELETE CASCADE,
  producto_id BIGINT NOT NULL REFERENCES public.productos(id) ON DELETE CASCADE,
  creado_en TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL,
  UNIQUE(usuario_id, producto_id)
);

-- 2.7 Tabla de Logs de Auditoría para la Consola Administrativa
CREATE TABLE IF NOT EXISTS public.logs_auditoria (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  uuid UUID DEFAULT gen_random_uuid() UNIQUE NOT NULL,
  usuario_id BIGINT REFERENCES public.usuarios(id) ON DELETE SET NULL,
  accion VARCHAR(100) NOT NULL,
  modulo VARCHAR(50) NOT NULL,
  detalle JSONB DEFAULT '{}'::jsonb,
  ip_origen VARCHAR(45),
  creado_en TIMESTAMPTZ DEFAULT timezone('utc'::text, now()) NOT NULL
);

